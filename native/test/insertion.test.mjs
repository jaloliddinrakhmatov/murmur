// These tests use the real system clipboard. The user's clipboard is snapshotted first and
// restored at the end, using the same snapshot/restore mechanism under test.
import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const native = require("../index.cjs");
const perms = native.permissionStatus();
let original;

before(() => {
  original = native.clipboardSnapshot();
});

after(() => {
  const r = native.clipboardRestore(original, native.clipboardChangeCount());
  assert.equal(r.restored, true, "user clipboard restored");
});

test("writes dictated text with clipboard-manager transient markers", () => {
  const before = native.clipboardChangeCount();
  const cc = native.clipboardWriteText("murmur test ✓ привет o‘zbek", true);
  assert.ok(cc > before);
  assert.equal(native.clipboardReadText(), "murmur test ✓ привет o‘zbek");
  const types = native.clipboardTypes();
  for (const t of [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
  ]) {
    assert.ok(types.includes(t), `${t} in ${types}`);
  }
});

test("restores the previous clipboard when nothing newer was copied", () => {
  native.clipboardWriteText("previous user content", false);
  const snap = native.clipboardSnapshot();
  const cc = native.clipboardWriteText("dictation", true);
  assert.deepEqual(native.clipboardRestore(snap, cc), {
    restored: true,
    reason: "restored",
  });
  assert.equal(native.clipboardReadText(), "previous user content");
});

test("never overwrites content the user copied after our write", () => {
  native.clipboardWriteText("previous user content", false);
  const snap = native.clipboardSnapshot();
  const cc = native.clipboardWriteText("dictation", true);
  native.clipboardWriteText(
    "user copied this during the restore window",
    false,
  );
  assert.deepEqual(native.clipboardRestore(snap, cc), {
    restored: false,
    reason: "clipboard-changed-since-write",
  });
  assert.equal(
    native.clipboardReadText(),
    "user copied this during the restore window",
  );
});

test("unknown or reused snapshot ids are refused", () => {
  const snap = native.clipboardSnapshot();
  native.clipboardRestore(snap, native.clipboardChangeCount());
  assert.equal(
    native.clipboardRestore(snap, native.clipboardChangeCount()).reason,
    "unknown-snapshot",
  );
});

test("resolves the paste key for the current layout", () => {
  const k = native.pasteKeycode();
  assert.ok(k, "layout data available");
  assert.equal(typeof k.keycodeToPost, "number");
});

test("layout-aware paste keycodes for installed layouts", () => {
  const byId = Object.fromEntries(
    native.pasteKeycodesForInstalledLayouts().map((l) => [l.sourceId, l]),
  );
  assert.equal(byId["com.apple.keylayout.US"]?.keycode, 9);
  if (byId["com.apple.keylayout.Dvorak"]) {
    assert.equal(
      byId["com.apple.keylayout.Dvorak"].keycode,
      47,
      "Dvorak 'v' is on the ANSI period key",
    );
    assert.notEqual(
      byId["com.apple.keylayout.Dvorak"].ansiVTypes,
      "v",
      "posting ANSI_V would not paste",
    );
  }
  if (byId["com.apple.keylayout.DVORAK-QWERTYCMD"]) {
    assert.equal(
      byId["com.apple.keylayout.DVORAK-QWERTYCMD"].keycode,
      9,
      "QWERTY while Command is held",
    );
  }
});

test("detects the frontmost app without any permission", () => {
  const app = native.frontmostApp();
  assert.ok(app && app.pid > 0, JSON.stringify(app));
});

test("rejects insertion while Secure Event Input is on (password field signal)", () => {
  native.clipboardWriteText("sentinel", false);
  const cc = native.clipboardChangeCount();
  assert.equal(native.testSetSecureEventInput(true), 0);
  try {
    assert.equal(native.permissionStatus().secureEventInput, true);
    const r = native.insertText("my password is hunter2");
    assert.equal(r.strategy, "rejected");
    assert.equal(r.reason, "secure-event-input");
    assert.equal(native.clipboardChangeCount(), cc, "nothing copied either");
  } finally {
    native.testSetSecureEventInput(false);
  }
  assert.equal(native.permissionStatus().secureEventInput, false);
});

test(
  "without Accessibility the focused element is unknown and reported as such",
  { skip: perms.accessibility && "Accessibility is granted here" },
  () => {
    const f = native.focusedElement();
    assert.equal(f.ok, false);
    assert.equal(f.error, "accessibility-not-trusted");
  },
);

test(
  "without AX or event posting, insertion falls back to clipboard-only",
  {
    skip:
      (perms.accessibility || perms.postEvents) && "permissions granted here",
  },
  () => {
    const r = native.insertText("fallback text");
    assert.equal(r.strategy, "clipboard-only");
    assert.equal(r.reason, "no-post-event-permission");
    assert.equal(r.ok, true);
    assert.equal(native.clipboardReadText(), "fallback text");
    assert.ok(r.steps.includes("focus:accessibility-not-trusted"));
  },
);

test("readSelection (Stage 9C): never throws; reads only the selection, nothing from secure fields", () => {
  const s = native.readSelection();
  assert.equal(typeof s.ok, "boolean");
  if (!s.ok) {
    assert.match(
      s.error,
      /^(accessibility-not-trusted|no-focused-element|ax-error:-?\d+)$/,
    );
    assert.equal(s.text ?? null, null);
  }
  if (s.isSecure) assert.equal(s.text ?? null, null);
  if (!perms.accessibility) assert.equal(s.ok, false);
});

test("pressReturn refuses when the expected app is not in front (never posts a key)", () => {
  // pid -1 is never the frontmost app, so the guard refuses before any event is created.
  const r = native.pressReturn(0, -1);
  assert.equal(r.ok, false);
  assert.equal(r.reason, "target-changed");
  assert.deepEqual(r.steps, []);
});

test("copySelection refuses when the expected app is not in front (never posts a key)", () => {
  const before = native.clipboardChangeCount();
  const r = native.copySelection(-1, 0, 50);
  assert.equal(r.ok, false);
  assert.equal(r.reason, "target-changed");
  assert.equal(r.text, undefined);
  assert.equal(
    native.clipboardChangeCount(),
    before,
    "the clipboard is untouched",
  );
});

test("readTextAround clamps absurd ranges instead of overflowing", () => {
  for (const [at, before, after] of [
    [Number.MAX_VALUE, 4294967295, 4294967295],
    [-1e300, 4294967295, 4294967295],
    [NaN, 0, 0],
  ]) {
    const r = native.readTextAround(at, before, after);
    assert.equal(typeof r.ok, "boolean");
  }
});
